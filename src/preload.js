const {contextBridge,ipcRenderer}=require("electron");
contextBridge.exposeInMainWorld("saeed",{
 chat:(text,image=null)=>ipcRenderer.invoke("chat",{text,image}),
 capture:()=>ipcRenderer.invoke("capture"),
 getHistory:()=>ipcRenderer.invoke("history:get"),
 newChat:()=>ipcRenderer.invoke("history:new"),
 openChat:id=>ipcRenderer.invoke("history:open",id),
 deleteChat:()=>ipcRenderer.invoke("history:delete"),
 clearHistory:()=>ipcRenderer.invoke("history:clear"),
 getSettings:()=>ipcRenderer.invoke("settings:get"),
 setSettings:s=>ipcRenderer.invoke("settings:set",s),
 moveWindowBy:(dx,dy)=>ipcRenderer.send("window:move-by",dx,dy),
 showChat:()=>ipcRenderer.send("window:show-chat"),
 openSettings:()=>ipcRenderer.send("window:open-settings"),
 closeSettings:()=>ipcRenderer.send("settings:close"),
 minimizeWindow:()=>ipcRenderer.send("window:minimize"),
 hideWindow:()=>ipcRenderer.send("window:hide"),
 quit:()=>ipcRenderer.send("app:quit"),
 checkForUpdates:()=>ipcRenderer.invoke("updates:check"),
 installUpdate:info=>ipcRenderer.invoke("updates:install",info),
 onUpdateProgress:f=>ipcRenderer.on("update:progress",(_,p)=>f(p)),
 onUpdateStatus:f=>ipcRenderer.on("update:status",(_,s)=>f(s)),
 onEvent:f=>ipcRenderer.on("agent:event",(_,e)=>f(e)),
 onConfirmation:f=>ipcRenderer.on("agent:confirm",(_,e)=>f(e)),
 respondConfirmation:(id,approved)=>ipcRenderer.invoke("agent:confirm-response",id,approved),
 onScreenCapture:f=>ipcRenderer.on("screen:capture",(_,e)=>f(e)),
 onShowChat:f=>ipcRenderer.on("chat:show",()=>f()),
 onShowSettings:f=>ipcRenderer.on("settings:show",()=>f()),
 onMicMode:f=>ipcRenderer.on("mic:mode",(_,mode)=>f(mode)),
 onHistoryCleared:f=>ipcRenderer.on("history:cleared",()=>f()),
 startRealtime:o=>ipcRenderer.invoke("realtime:start",o||{}),
 stopRealtime:()=>ipcRenderer.invoke("realtime:stop"),
 sendRealtimeAudio:b=>ipcRenderer.invoke("realtime:audio",b),
 sendRealtimeText:t=>ipcRenderer.invoke("realtime:text",t),
 cancelRealtime:()=>ipcRenderer.invoke("realtime:cancel"),
 onRealtimeState:f=>ipcRenderer.on("realtime:state",(_,state,message)=>f(state,message)),
 onRealtimeAudio:f=>ipcRenderer.on("realtime:audio",(_,b)=>f(b)),
 onRealtimeAssistantDelta:f=>ipcRenderer.on("realtime:assistant-delta",(_,t)=>f(t)),
 onRealtimeAssistantFinal:f=>ipcRenderer.on("realtime:assistant-final",(_,t)=>f(t)),
 onRealtimeUserDelta:f=>ipcRenderer.on("realtime:user-delta",(_,t)=>f(t)),
 onRealtimeUserFinal:f=>ipcRenderer.on("realtime:user-final",(_,t)=>f(t)),
 onRealtimeDone:f=>ipcRenderer.on("realtime:done",(_,s)=>f(s)),
 onRealtimeError:f=>ipcRenderer.on("realtime:error",(_,e)=>f(e)),
 characterReady:data=>ipcRenderer.send("character:ready",data),
selectCharacter:()=>ipcRenderer.invoke("character:select"),
getCharacter:()=>ipcRenderer.invoke("character:current"),
pickAttachment:()=>ipcRenderer.invoke("attachment:pick"),
onCharacterPath:f=>ipcRenderer.on("character:path",(_,p)=>f(p)),
onEmail:f=>ipcRenderer.on("email:new",(_,mail)=>f(mail)),
checkEmail:()=>ipcRenderer.invoke("email:check"),
signoutEmail:()=>ipcRenderer.invoke("email:signout")
});